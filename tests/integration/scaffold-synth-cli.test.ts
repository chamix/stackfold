import { mkdir, mkdtemp, readFile, rm, stat, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { runScaffoldSynth, type ScaffoldSynthCommandDependencies } from '../../src/cli/commands/scaffoldSynth.js';
import { compileScaffold, type ScaffoldDefinition } from '../../src/core/authoring.js';
import { JsonLogicExpressionEvaluator } from '../../src/infra/expressionEvaluator.js';

/** stackfold's own repo root, derived from this file's location (ESM-safe — no bare __dirname). */
const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), '../..');
const BUILDER_URL = pathToFileURL(join(REPO_ROOT, 'src/authoring/builder.ts')).href;
const TEMPLATE_LOADER_URL = pathToFileURL(join(REPO_ROOT, 'src/authoring/templateLoader.ts')).href;

let root: string;
let pluginDir: string;
let outputRoot: string;

beforeEach(async () => {
  root = await mkdtemp(join(tmpdir(), 'stackfold-scaffold-synth-cli-'));
  pluginDir = join(root, 'author');
  outputRoot = join(root, 'output');
  await mkdir(pluginDir, { recursive: true });
  await mkdir(outputRoot, { recursive: true });

  // A governing package.json declaring "type": "module" — the same
  // condition every real `src/plugins/<id>/` directory already inherits
  // from this repo's own root package.json (see scaffoldSynth.ts's own
  // header comment, "Precondition").
  await writeFile(join(pluginDir, 'package.json'), '{"type":"module"}\n', 'utf8');
});

afterEach(async () => {
  await rm(root, { recursive: true, force: true });
});

function makeDeps(): ScaffoldSynthCommandDependencies & { stdoutLines: string[]; stderrLines: string[] } {
  const stdoutLines: string[] = [];
  const stderrLines: string[] = [];
  return {
    stdout: (line) => stdoutLines.push(line),
    stderr: (line) => stderrLines.push(line),
    cwd: () => outputRoot,
    stdoutLines,
    stderrLines,
  };
}

describe('stackfold scaffold synth <dir> — real end-to-end', () => {
  it('loads a real scaffold.ts + sibling .hbs file and writes a real, valid scaffold.json', async () => {
    await writeFile(
      join(pluginDir, 'greeting.hbs'),
      '# {{appName}}\n\nGenerated by the scaffold synth CLI integration test.\n',
      'utf8'
    );
    await writeFile(
      join(pluginDir, 'scaffold.ts'),
      `import { defineScaffold, file, mkdir } from '${BUILDER_URL}';
import { loadTemplate } from '${TEMPLATE_LOADER_URL}';

const readmeContent = loadTemplate(import.meta.dirname, 'greeting.hbs');

export default defineScaffold({
  id: 'synth-cli-fixture',
  description: 'CLI integration fixture plugin.',
  questions: [{ id: 'appName', message: 'App name', type: 'input', default: 'fixture-app' }],
  steps: [mkdir('src'), file('README.md', readmeContent)],
});
`,
      'utf8'
    );

    const deps = makeDeps();
    const code = await runScaffoldSynth(pluginDir, deps);

    expect(deps.stderrLines).toEqual([]);
    expect(code).toBe(0);

    const outputPath = join(outputRoot, 'src', 'plugins', 'synth-cli-fixture', 'scaffold.json');
    const raw = await readFile(outputPath, 'utf8');
    const parsed = JSON.parse(raw) as ScaffoldDefinition;

    expect(parsed.id).toBe('synth-cli-fixture');
    expect(parsed.steps).toEqual([
      { action: 'mkdir', params: { path: 'src' } },
      {
        action: 'writeFile',
        params: { path: 'README.md', content: '# {{appName}}\n\nGenerated by the scaffold synth CLI integration test.\n' },
      },
    ]);

    // Byte-valid JSON that compileScaffold() can also consume directly.
    expect(() => compileScaffold(parsed, new JsonLogicExpressionEvaluator())).not.toThrow();

    expect(deps.stdoutLines.some((line) => line.includes(outputPath))).toBe(true);
  });

  it('supports a thunk (function) default export, not just a plain object', async () => {
    await writeFile(
      join(pluginDir, 'scaffold.ts'),
      `import { defineScaffold, gitInit } from '${BUILDER_URL}';

export default function build() {
  return defineScaffold({
    id: 'synth-cli-thunk-fixture',
    description: 'Thunk-exported fixture plugin.',
    questions: [],
    steps: [gitInit()],
  });
}
`,
      'utf8'
    );

    const deps = makeDeps();
    const code = await runScaffoldSynth(pluginDir, deps);

    expect(code).toBe(0);
    const outputPath = join(outputRoot, 'src', 'plugins', 'synth-cli-thunk-fixture', 'scaffold.json');
    const parsed = JSON.parse(await readFile(outputPath, 'utf8')) as ScaffoldDefinition;
    expect(parsed.steps).toEqual([{ action: 'gitInit', params: {} }]);
  });

  it('supports a named "scaffold" export when there is no default export', async () => {
    await writeFile(
      join(pluginDir, 'scaffold.ts'),
      `import { defineScaffold, npmInstall } from '${BUILDER_URL}';

export const scaffold = defineScaffold({
  id: 'synth-cli-named-export-fixture',
  description: 'Named-export fixture plugin.',
  questions: [],
  steps: [npmInstall()],
});
`,
      'utf8'
    );

    const deps = makeDeps();
    const code = await runScaffoldSynth(pluginDir, deps);

    expect(code).toBe(0);
    const outputPath = join(outputRoot, 'src', 'plugins', 'synth-cli-named-export-fixture', 'scaffold.json');
    const parsed = JSON.parse(await readFile(outputPath, 'utf8')) as ScaffoldDefinition;
    expect(parsed.steps).toEqual([{ action: 'npmInstall', params: {} }]);
  });

  it('exits 1 and writes nothing when the ScaffoldDefinition fails structural validation', async () => {
    await writeFile(
      join(pluginDir, 'scaffold.ts'),
      `export default {
  id: '',
  description: 'Invalid: empty id.',
  questions: [],
  steps: [],
};
`,
      'utf8'
    );

    const deps = makeDeps();
    const code = await runScaffoldSynth(pluginDir, deps);

    expect(code).toBe(1);
    expect(deps.stderrLines.length).toBeGreaterThan(0);
    await expect(stat(join(outputRoot, 'src', 'plugins'))).rejects.toThrow();
  });

  it('exits 1 and writes nothing when the smoke test fails (unknown action)', async () => {
    await writeFile(
      join(pluginDir, 'scaffold.ts'),
      `export default {
  id: 'synth-cli-bad-action-fixture',
  description: 'Invalid: unknown action.',
  questions: [],
  steps: [{ action: 'thisActionDoesNotExist', params: {} }],
};
`,
      'utf8'
    );

    const deps = makeDeps();
    const code = await runScaffoldSynth(pluginDir, deps);

    expect(code).toBe(1);
    expect(deps.stderrLines.join('\n')).toMatch(/thisActionDoesNotExist|smoke test/);
    await expect(stat(join(outputRoot, 'src', 'plugins'))).rejects.toThrow();
  });

  it('exits 1 with a clear error when scaffold.ts does not exist', async () => {
    const deps = makeDeps();
    const code = await runScaffoldSynth(pluginDir, deps);

    expect(code).toBe(1);
    expect(deps.stderrLines.join('\n')).toContain('scaffold.ts');
  });
});
