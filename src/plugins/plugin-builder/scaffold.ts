/**
 * `plugin-builder` — stackfold's own meta-plugin (Task 034,
 * .agents/specs/plugin-builder-scaffold-authoring.md; reauthored for Task
 * 042, .agents/specs/042-plugin-builder-ts-authoring.md, SK-ADR-003).
 * `stackfold init plugin-builder <dir>` scaffolds a brand-new stackfold
 * plugin — itself authored the TS way too (`scaffold.ts` + `.hbs` +
 * `synth`, per this task's purpose #2: plugin-builder is now the live
 * reference for "how a stackfold plugin is authored today") — and
 * registers the result into stackfold's own `PluginRegistry` by patching
 * `src/cli/index.ts` via the general-purpose `patchFile` hook action
 * (D2/D6, Task 034, unchanged).
 *
 * An ordinary `defineScaffold()`-authored plugin, exactly like
 * `src/plugins/electron-stackfold/` in registration *style* — no TS
 * factory function, no injected `gitUserName` default (Task 042, confirmed
 * decision — Open item 1, option (a)). The "author" question below
 * therefore carries a plain, static `default: ''` — the same convention
 * `web-app`/`electron-ts` already use when there is no override — not a
 * dynamic `git config user.name` lookup.
 *
 * Compile source (Task 042 review follow-up, review_report.md Blocking
 * #1): unlike `electron-stackfold`, `cli/index.ts` does **not** compile
 * this plugin from its committed `scaffold.json`. JSON cannot carry
 * function values, so synthesizing through `scaffold.json` silently drops
 * every `validate: toValidate(...)` closure declared on the 4 questions
 * below — `core/orchestrator.ts`'s `resolveAnswers()` falls through to
 * "always valid" whenever `q.validate` is `undefined`, so the real `npx
 * stackfold init plugin-builder` runtime path accepted invalid input (e.g.
 * a non-kebab-case `pluginId`) with zero rejection. `cli/index.ts` now
 * imports this module's own `scaffold.js` directly (`compileScaffold(
 * (await import('../plugins/plugin-builder/scaffold.js')).default,
 * expressionEvaluator)`), so the `validate` closures stay live.
 * `scaffold.json` stays committed alongside this file — regenerated by a
 * real `stackfold scaffold synth` invocation, same as always — as the
 * synth-verified canonical artifact proving the synth pipeline round-trips
 * this plugin correctly (this task's purpose #1); it just isn't what gets
 * loaded at runtime for plugin-builder itself anymore. (The *generated*
 * end-user plugin's own `scaffold.json`, written by the `writeFile` steps
 * below, is a different file per generated plugin, and is still always
 * loaded as JSON when registering that plugin — it has no TS
 * factory/validate concerns of its own, so JSON is fine there.)
 *
 * Intended to be run from the root of a stackfold checkout — targeting
 * `src/plugins/<pluginId>` — since its whole point (purpose #3 of the
 * spec) is extending stackfold itself. The generated files' relative
 * import depths (`../../authoring/builder.js`/`../../core/authoring.js`
 * from the generated plugin's own files, `../plugins/<id>/...` from
 * `src/cli/index.ts`) assume exactly that layout.
 *
 * `postInit` hook order (D-C, non-negotiable): (1) `runHookCommand` →
 * shells out to `stackfold scaffold synth src/plugins/<pluginId>` against
 * the real invoking process's cwd (never `targetDir` — see
 * `core/authoring.ts`'s `runHookCommand` header comment); (2) `patchFile`
 * → the shared import line; (3) `patchFile` → the pluginId-specific
 * registry entry. Order is the whole mechanism: `runHooks()`
 * (`core/orchestrator.ts`) aborts on the first handler that throws, so a
 * failed synth (a malformed generated `scaffold.ts`, a broken template)
 * never leaves `src/cli/index.ts` patched to import a `scaffold.json` that
 * was never written — no new error-handling code, per D-C.
 *
 * `pluginIdSchema` below is a new, kebab-case zod schema, in the same
 * style as `core/validation.ts`'s `appNameSchema` — defined locally rather
 * than added to `core/validation.ts` itself, which is outside this task's
 * declared scope (.agents/current_scope.json); this keeps the *convention*
 * shared without requiring an edit to a file this task was not authorized
 * to touch.
 */
import { z } from 'zod';
import { defineScaffold, step } from '../../authoring/builder.js';
import { loadTemplate } from '../../authoring/templateLoader.js';
import { authorSchema, descriptionSchema, toValidate } from '../../core/validation.js';

export const DEFAULT_PLUGIN_ID = 'my-plugin';
export const DEFAULT_DISPLAY_NAME = 'My Plugin';
export const DEFAULT_PLUGIN_DESCRIPTION = 'A stackfold plugin.';
export const DEFAULT_AUTHOR = '';

/**
 * Kebab-case: lowercase letters/digits, single hyphens, starting with a
 * letter — same convention/style as `core/validation.ts`'s `appNameSchema`
 * (trim, bounded length, a `refine` with a clear message), not a parallel
 * validation scheme. See this module's header comment for why this lives
 * here instead of in `core/validation.ts`.
 */
export const pluginIdSchema = z
  .string()
  .trim()
  .min(1, 'Plugin id must not be empty.')
  .max(100, 'Plugin id must be 100 characters or fewer.')
  .refine(
    (v) => /^[a-z][a-z0-9]*(-[a-z0-9]+)*$/.test(v),
    'Plugin id must be kebab-case: lowercase letters/digits, single hyphens, starting with a letter.'
  );

/**
 * The 3 sibling `.hbs` templates loaded here, once, at module-evaluation
 * time (same as any other `scaffold.ts`'s own `loadTemplate()` calls —
 * `src/authoring/templateLoader.ts`'s header comment): the generated
 * plugin's own `templates/readme.md.hbs`, `scaffold.ts`, and
 * `scaffold.test.ts`. Each is Handlebars-rendered against plugin-builder's
 * *own* answers (`writeFile`'s existing `content` mechanism,
 * `core/authoring.ts`) when `buildBlueprint()` runs below — the
 * `{{pluginId}}`/`{{displayName}}`/`{{description}}` placeholders inside
 * each one are substituted at that point, so the generated plugin's own
 * files land on disk with those values already literal, never left as
 * Handlebars syntax the generated plugin would need to re-render itself
 * (it declares no questions of its own — D-E).
 */
const README_TEMPLATE = loadTemplate(import.meta.dirname, 'templates/readme.md.hbs');
const SCAFFOLD_TS_TEMPLATE = loadTemplate(import.meta.dirname, 'templates/scaffold.ts.hbs');
const SCAFFOLD_TEST_TS_TEMPLATE = loadTemplate(import.meta.dirname, 'templates/scaffold.test.ts.hbs');

/** `src/cli/index.ts`'s one-time anchor markers (purely additive — see that file). */
const IMPORTS_ANCHOR = '// stackfold-plugin-imports:end';
const REGISTRY_ANCHOR = '// stackfold-plugin-registry:end';

export default defineScaffold({
  id: 'plugin-builder',
  description:
    'Scaffolds a brand-new stackfold plugin, authored as a TS scaffold.ts + synth, and ' +
    "registers it into stackfold's own plugin registry.",
  help: {
    name: 'Plugin Builder',
    details:
      'Generates a new stackfold plugin as a TS-authored scaffold.ts + sibling .hbs templates under ' +
      'src/plugins/<pluginId>/, synthesizes its canonical scaffold.json via a real `stackfold scaffold ' +
      'synth` invocation, and registers it into src/cli/index.ts via the patchFile hook action. Run from ' +
      'the root of a stackfold checkout.',
  },

  questions: [
    {
      id: 'pluginId',
      message: 'Plugin id (kebab-case, e.g. "my-cool-plugin")',
      type: 'input',
      default: DEFAULT_PLUGIN_ID,
      validate: toValidate(pluginIdSchema),
    },
    {
      id: 'displayName',
      message: 'Display name (shown in `stackfold list`/`info`)',
      type: 'input',
      default: DEFAULT_DISPLAY_NAME,
      validate: toValidate(descriptionSchema),
    },
    {
      id: 'description',
      message: 'Short description (shown in listings)',
      type: 'input',
      default: DEFAULT_PLUGIN_DESCRIPTION,
      validate: toValidate(descriptionSchema),
    },
    {
      id: 'author',
      message: 'Author',
      type: 'input',
      default: DEFAULT_AUTHOR,
      validate: toValidate(authorSchema),
    },
  ],

  // Dynamic, pluginId-prefixed paths — `step('writeFile', ...)` directly
  // (not the `file()` sugar, which only accepts a literal `path: string`):
  // each path is a JSON Logic expression resolved against answers by the
  // existing `resolveParams()`/`resolveValue()` pipeline
  // (`core/authoring.ts`), same mechanism v1 already used. `content` is
  // always one of the 3 literal, author-written `.hbs` templates loaded
  // above — never expression-resolved (`writeFile`'s own `literalKeys`).
  steps: [
    step('writeFile', {
      path: { cat: [{ var: 'pluginId' }, '/templates/readme.md.hbs'] },
      content: README_TEMPLATE,
    }),
    step('writeFile', {
      path: { cat: [{ var: 'pluginId' }, '/scaffold.ts'] },
      content: SCAFFOLD_TS_TEMPLATE,
      // Task 042 review follow-up (review_report.md Blocking #2):
      // SCAFFOLD_TS_TEMPLATE interpolates `displayName`/`description` into
      // single-quoted TS string literals (`id: '{{pluginId}}'`,
      // `description: '{{description}}'`, `help: { name: '{{displayName}}'
      // }`). `pluginId` itself needs no escaping — its own kebab-case
      // schema above already excludes apostrophes — but `displayName`/
      // `description` are ordinary free text where an apostrophe (e.g.
      // "It's a thing") would otherwise produce an unterminated string
      // literal. Not applied to the readme.md.hbs step above (markdown,
      // apostrophes are harmless there) or the scaffold.test.ts.hbs step
      // below (interpolates only `pluginId`, already apostrophe-free).
      jsEscapeKeys: ['displayName', 'description'],
    }),
    step('writeFile', {
      path: { cat: [{ var: 'pluginId' }, '/scaffold.test.ts'] },
      content: SCAFFOLD_TEST_TS_TEMPLATE,
    }),
  ],

  hooks: {
    postInit: [
      // (1) D-C/D-D: synth the just-written scaffold.ts into its canonical
      // scaffold.json, against the real cwd of the invoking process (never
      // `targetDir` — see core/authoring.ts's runHookCommand header
      // comment). Must run before either patchFile step below.
      step('runHookCommand', {
        command: 'npx',
        args: ['tsx', 'src/cli/index.ts', 'scaffold', 'synth', { cat: ['src/plugins/', { var: 'pluginId' }] }],
      }),
      // (2) Import line: the two symbols the registry-entry step below
      // needs to compile+register the generated manifest. Not
      // pluginId-specific — cli/index.ts's own wiring of plugin-builder
      // itself already adds these, so in practice this step is idempotent
      // from the very first run; it stays self-healing if that wiring
      // were ever missing.
      step('patchFile', {
        path: 'src/cli/index.ts',
        anchor: IMPORTS_ANCHOR,
        insert: {
          cat: [
            "import { compileScaffold } from '../core/authoring.js';\n",
            "import { JsonLogicExpressionEvaluator } from '../infra/expressionEvaluator.js';\n",
          ],
        },
        position: 'before',
      }),
      // (3) Registry entry: pluginId-specific — a fresh, unique line per
      // generated plugin. Only reachable once the synth step above has
      // actually produced a real scaffold.json (D-C's edge-case
      // invariant) — a dynamic import() of that JSON manifest, compiled
      // inline via the already-imported compileScaffold()/
      // expressionEvaluator.
      step('patchFile', {
        path: 'src/cli/index.ts',
        anchor: REGISTRY_ANCHOR,
        insert: {
          cat: [
            "  compileScaffold((await import('../plugins/",
            { var: 'pluginId' },
            "/scaffold.json', { with: { type: 'json' } })).default, expressionEvaluator),\n",
          ],
        },
        position: 'before',
      }),
    ],
  },
});
