/**
 * `scaffold synth`'s module emitter (SYNTH-001 / SK-ADR-009 Decision 2) — a
 * thin adapter over `esbuild`, the one piece of `src/authoring/synth.ts`'s
 * pipeline allowed to depend on a bundler at all. Exists so `synth.ts`
 * itself stays bundler-agnostic (DIP: it depends on the `ScaffoldModuleEmitter`
 * interface below, not on `esbuild` directly) and so `synth.ts`'s own tests
 * can inject a fake emitter without ever invoking a real bundler.
 *
 * Lazy import (`await import('esbuild')` inside `emit()`, never at this
 * module's top level): the same pattern `src/cli/commands/scaffoldSynth.ts`
 * already uses for `tsx`'s `tsImport` — starting the CLI for any other
 * command (`list`, `info`, `init`, `plugin register`, etc.) never loads
 * `esbuild` at all, since nothing outside `scaffold synth`'s own code path
 * ever calls `emit()`.
 *
 * Entry generation (D1): a generated stdin module that imports the
 * author's `scaffold.ts` by a *relative* specifier (so esbuild's own
 * relative-import resolution, not an absolute/`file://` one, decides what
 * gets bundled vs. left external — `packages: 'external'` only ever
 * applies to bare/package specifiers), then normalizes default-or-named
 * `scaffold`, value-or-thunk (sync or async) — exactly the same convention
 * `src/cli/commands/scaffoldSynth.ts`'s own `loadScaffoldDefinition()`
 * already uses — into a single, already-resolved `export default`.
 *
 * `src/authoring/` is tooling (a peer of `infra/`/`cli/`), not `core/` —
 * real `node:path` and a real bundler import are fine here, same
 * exception `templateLoader.ts`'s own header comment documents for this
 * layer.
 */
import { dirname, relative } from 'node:path';

/**
 * First line of every module this emitter produces — `synth.ts`'s own
 * stale-handling logic (SK-ADR-009 Decision 4) uses this exact string to
 * tell "a `scaffold.js` `synth` itself generated, now stale" apart from "a
 * foreign hand-written/`tsc`-built one it must never touch".
 */
export const GENERATED_MODULE_BANNER = '// @generated by stackfold scaffold synth - do not edit';

/**
 * Injectable port (DIP) — `realEsbuildEmitter` is the only production
 * implementation; `tests/unit/authoring-synth.test.ts` injects a fake that
 * returns real, hand-written ESM text (never a mock of `esbuild` itself)
 * so `synth.ts`'s own orchestration (parity, atomic writes, stale
 * handling) can be exercised without paying for a real bundler run.
 * `tests/unit/emit-module.test.ts` is the one place required to use the
 * real implementation.
 */
export interface ScaffoldModuleEmitter {
  /**
   * Bundles `scaffoldTsPath` into a self-contained ESM module string whose
   * default export is the already-resolved `ScaffoldDefinition` (closures
   * intact). Never writes anything to disk itself — `synth.ts` owns every
   * write, so it alone is responsible for the verify-then-atomic-rename
   * invariant (SK-ADR-009 Decision 3).
   */
  emit(scaffoldTsPath: string): Promise<string>;
}

/**
 * Builds the generated stdin entry module. `resolveDir` (the directory
 * `scaffoldTsPath` itself lives in) is what esbuild resolves this entry's
 * own relative import against when given as `stdin.resolveDir` — so the
 * specifier here must be relative to `resolveDir`, not an absolute path,
 * for esbuild's `packages: 'external'` option to correctly distinguish
 * "the author's own code, bundle it" from "a bare npm specifier, leave it
 * external" the same way it would for any ordinary multi-file project.
 */
function buildEntryCode(scaffoldTsPath: string, resolveDir: string): string {
  const specifier = toRelativeSpecifier(scaffoldTsPath, resolveDir);
  const noExportMessage = `"${scaffoldTsPath}" has no default export and no named "scaffold" export`;
  return `import * as __scaffoldModule from ${JSON.stringify(specifier)};

// Bracket/computed access (not static \`.default\`/\`.scaffold\` member
// access) deliberately: esbuild statically analyzes a namespace import's
// member accesses and warns "will always be undefined" when a fixture
// module doesn't declare one of the two — this normalization branch is
// supposed to tolerate exactly that, so the warning would be noise, not
// a real defect.
const __exported = 'default' in __scaffoldModule ? __scaffoldModule['default'] : __scaffoldModule['scaffold'];
if (__exported === undefined) {
  throw new Error(${JSON.stringify(noExportMessage)});
}
const __definition = typeof __exported === 'function' ? await __exported() : __exported;
export default await __definition;
`;
}

function toRelativeSpecifier(scaffoldTsPath: string, resolveDir: string): string {
  const rel = relative(resolveDir, scaffoldTsPath).split('\\').join('/');
  return rel.startsWith('.') ? rel : `./${rel}`;
}

/** Real, production `ScaffoldModuleEmitter` — the only one `scaffold synth` itself ever uses. */
export const realEsbuildEmitter: ScaffoldModuleEmitter = {
  async emit(scaffoldTsPath: string): Promise<string> {
    const resolveDir = dirname(scaffoldTsPath);
    const entryCode = buildEntryCode(scaffoldTsPath, resolveDir);

    // Lazily imported here (never at module top level) — see this module's
    // own header comment on why the CLI's other commands must never load
    // esbuild at all.
    const esbuild = await import('esbuild');
    const result = await esbuild.build({
      stdin: { contents: entryCode, resolveDir, sourcefile: 'scaffold-synth-entry.ts', loader: 'ts' },
      bundle: true,
      packages: 'external',
      format: 'esm',
      platform: 'node',
      target: 'node22',
      write: false,
      banner: { js: GENERATED_MODULE_BANNER },
      // Suppresses esbuild's own "will always be undefined" warning on
      // whichever of `.default`/`.scaffold` the author's module doesn't
      // declare — the entry's default-or-named normalization (this
      // module's own header comment) means exactly one of those two is
      // *expected* to be absent on any given author module; it's noise,
      // not a defect, and real syntax/resolution errors still throw
      // regardless of this setting.
      logLevel: 'silent',
    });

    const output = result.outputFiles?.[0];
    if (!output) {
      throw new Error(`emitScaffoldModule: esbuild produced no output bundling "${scaffoldTsPath}"`);
    }
    return output.text;
  },
};
